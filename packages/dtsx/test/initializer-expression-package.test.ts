for (const fixture of cases) {
  for (const producer of ['core', 'bun-plugin', 'native', 'typescript'] as const) {
    test(`${producer} preserves ${fixture.name} without inventing exports`, async () => {
      await checkDeclarationPackage(producer, {
        ...('filename' in fixture ? { filename: fixture.filename } : {}),
        source: fixture.source,
        positive: `${fixture.positive}; type ExpectedExports = ${fixture.exportedKeys.map(key => JSON.stringify(key)).join(' | ')}; type ActualExports = keyof typeof api; const exactExports: [ActualExports] extends [ExpectedExports] ? [ExpectedExports] extends [ActualExports] ? true : false : false = true`,
        negatives: [
          { code: 2322, content: fixture.negative },
          { code: 2339, content: 'api.number' },
          { code: 2339, content: 'api.string' },
        ],
      })
    })
  }
}
